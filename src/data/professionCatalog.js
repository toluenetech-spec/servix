export const CATEGORY_SLUGS = Object.keys(CATALOG);

function unique(list) {
  const seen = new Set();
  return list.filter((x) => {
    const k = x.toLowerCase();
    if (seen.has(k)) return false;
    seen.add(k);
    return true;
  });
}

/**
 * Options for `key` (titles | occupations | skills | certifications | serviceTypes)
 * in the given category. With no (or an unknown) category the lists of every
 * category are merged so the picker still works before a category is chosen.
 */
export function optionsFor(categorySlug, key) {
  const cat = categorySlug ? CATALOG[categorySlug] : null;
  let list = cat ? cat[key] ?? [] : CATEGORY_SLUGS.flatMap((slug) => CATALOG[slug][key] ?? []);
  if (key === 'certifications') list = [...list, ...GENERAL_CERTIFICATIONS];
  return unique(list);
}

export function categoryLabel(categorySlug) {
  return CATALOG[categorySlug]?.label ?? '';
}
